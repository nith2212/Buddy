"""
agent.py
--------
Core reasoning engine for Buddy V2.

Architecture — 3-layer state detection pipeline:
  Layer 1: Behavioral signals  — derived from task event history (postpone count, completions)
  Layer 2: Keyword signals     — fast scan of the user's raw message
  Layer 3: LLM classifier      — only invoked when layers 1 and 2 disagree on top state

All three layers feed into merge_hypotheses(), which produces a ranked list of
work-state hypotheses. The top state drives decide_intervention(), which queries
the RAG knowledge base for Buddy's behavioral framework, then uses an LLM
to pick the best intervention from a candidate set.

The final reply is generated by a second LLM call using a structured system prompt
that injects task history, user memory (with confidence + source), detected state,
and the chosen intervention goal.

V2 changes from hackathon:
- Memory is now a list of dicts (key, value, confidence, source) not flat KV
- System prompt injection shows confidence + source so Buddy knows how much to trust each entry
- update_memory() calls use new key namespace (buddy.*, onboarding.*) and pass confidence + source
- log_event() calls use new signature (user_id, event_type, note, task_id, source)
- log_progress_if_needed() returns event_id from log_event, not just the event dict
"""

import os
import json
from groq import Groq
from dotenv import load_dotenv
from rag import query_buddy_framework
from tools import (
    get_task_history, get_user_memory,
    get_conversation_history, save_conversation_turn,
    log_event, update_memory,
)

load_dotenv()

client = Groq(api_key=os.getenv("GROQ_API_KEY"))


# ── Memory helpers ────────────────────────────────────────────────────────────

def memory_to_dict(memory: list[dict]) -> dict:
    """
    Convert the V2 memory list (key, value, confidence, source) to a flat
    {key: value} dict for backwards-compatible code paths that just need values.
    When duplicate semantic keys exist, highest-confidence row wins (list is
    already sorted by confidence DESC from get_user_memory()).
    """
    result = {}
    for row in memory:
        if row["key"] not in result:  # first = highest confidence
            result[row["key"]] = row["value"]
    return result


def format_memory_for_prompt(memory: list[dict]) -> str:
    """
    Format memory rows for injection into LLM system prompt.
    Shows value, confidence, and source so Buddy can calibrate trust.

    Example output line:
      - buddy.last_detected_state: fatigue (confidence: 0.50, source: buddy)
      - echo.belief.self_language: calls herself lazy when describing confusion (confidence: 0.82, source: echo)
      - onboarding.procrastination_style: overwhelmed (confidence: 0.30, source: onboarding)
    """
    if not memory:
        return "No memory entries yet."
    lines = []
    for row in memory:
        lines.append(
            f"- {row['key']}: {row['value']} "
            f"(confidence: {row['confidence']:.2f}, source: {row['source']})"
        )
    return "\n".join(lines)


# ── Layer 1: Behavioral signal detection ─────────────────────────────────────

def detect_behavioral_state(task_history: dict) -> list:
    events = task_history.get("events", [])
    task   = task_history.get("task", {})

    if task and task.get("status") == "completed":
        return [
            {"state": "recovery",  "confidence": 0.70},
            {"state": "momentum",  "confidence": 0.30},
        ]

    postpone_count  = sum(1 for e in events if e["event_type"] == "postponed")
    completed_count = sum(1 for e in events if e["event_type"] == "completed")

    hypotheses = []

    if postpone_count >= 3:
        hypotheses.append({"state": "avoidance", "confidence": 0.70})
        hypotheses.append({"state": "overwhelm", "confidence": 0.20})
    elif postpone_count == 2:
        hypotheses.append({"state": "avoidance", "confidence": 0.50})
        hypotheses.append({"state": "overwhelm", "confidence": 0.30})
        hypotheses.append({"state": "fatigue",   "confidence": 0.20})
    elif postpone_count == 1:
        hypotheses.append({"state": "fatigue",   "confidence": 0.45})
        hypotheses.append({"state": "avoidance", "confidence": 0.35})
        hypotheses.append({"state": "overwhelm", "confidence": 0.20})

    if completed_count > 0 and postpone_count == 0:
        hypotheses = [
            {"state": "momentum",   "confidence": 0.80},
            {"state": "confidence", "confidence": 0.20},
        ]

    if not hypotheses:
        hypotheses = [
            {"state": "ambiguity", "confidence": 0.60},
            {"state": "avoidance", "confidence": 0.40},
        ]

    return hypotheses


# ── Layer 2: Keyword signal detection ────────────────────────────────────────

KEYWORD_MAP = {
    "overwhelm":   ["too much", "overwhelming", "a lot", "don't know where", "so much"],
    "ambiguity":   ["don't know how", "not sure", "confused", "unclear", "where to start"],
    "fatigue":     ["tired", "exhausted", "drained", "sleepy", "no energy"],
    "avoidance":   ["later", "tomorrow", "not now", "maybe later", "skip"],
    "motivated":   ["let's go", "ready", "let's do", "pumped", "excited"],
    "anxious":     ["scared", "anxious", "nervous", "stressed"],
    "frustration": ["annoying", "stop", "enough", "leave me alone", "ugh", "irritating", "quit it"],
    "deflection":  ["lol", "boring", "i dont want to", "i don't want to", "whatever", "meh"],
    "planning":    ["i can", "i'll", "i will", "let me", "i'm going to", "i think i'll", "maybe i'll", "i could start"],
    "recovery":    ["yayyy", "yay", "done", "finished", "completed", "i did it", "got it done"],
}

def detect_keyword_state(user_message: str) -> dict | None:
    msg = user_message.lower()
    for state, keywords in KEYWORD_MAP.items():
        for kw in keywords:
            if kw in msg:
                return {"state": state, "confidence": 0.75}
    return None


# ── Layer 3: LLM classifier ───────────────────────────────────────────────────

def llm_classify_state(user_message: str, behavioral_hypotheses: list) -> list:
    states = [h["state"] for h in behavioral_hypotheses]
    prompt = (
        f"You are a work-state classifier. Based on the user's message, rank these states by likelihood.\n"
        f"States to rank: {', '.join(states)}\n"
        f"User message: \"{user_message}\"\n\n"
        f"Respond ONLY with a JSON array like:\n"
        f"[{{\"state\": \"overwhelm\", \"confidence\": 0.60}}, ...]\n"
        f"No preamble, no markdown, no explanation."
    )
    response = client.chat.completions.create(
        model="llama-3.1-8b-instant",
        messages=[{"role": "user", "content": prompt}],
        temperature=0.3,
    )
    try:
        return json.loads(response.choices[0].message.content)
    except Exception:
        return behavioral_hypotheses


# ── Hypothesis merger ─────────────────────────────────────────────────────────

def merge_hypotheses(behavioral: list, keyword: dict | None, llm: list | None) -> list:
    scores = {}

    for h in behavioral:
        scores[h["state"]] = scores.get(h["state"], 0) + h["confidence"] * 0.4

    if keyword:
        scores[keyword["state"]] = scores.get(keyword["state"], 0) + keyword["confidence"] * 0.35

    if llm:
        for h in llm:
            scores[h["state"]] = scores.get(h["state"], 0) + h["confidence"] * 0.25

    total  = sum(scores.values()) or 1
    merged = [{"state": s, "confidence": round(c / total, 2)} for s, c in scores.items()]
    return sorted(merged, key=lambda x: x["confidence"], reverse=True)


# ── Candidate interventions ───────────────────────────────────────────────────

CANDIDATE_INTERVENTIONS = {
    "break_down_task":         "Break the task into smaller, more manageable pieces",
    "surface_smallest_step":   "Identify the single smallest possible next action",
    "clarify_first_step":      "Help clarify exactly what the first step looks like",
    "reschedule_with_empathy": "Acknowledge fatigue and suggest a better time to work",
    "celebrate_progress":      "Acknowledge progress made so far, build momentum",
    "ease_off":                "Stop questioning, back off, just be present and warm",
    "name_the_pattern":        "Gently name what's happening without judgment — call out avoidance directly but kindly, no rescheduling offer",
    "affirm_and_release":      "User has stated a plan — affirm it briefly and let them go act, no more questions",
}


def decide_intervention(
    hypotheses: list,
    memory: list[dict],
    observations: list,
) -> dict:
    """
    Uses RAG + LLM reasoning to pick the best intervention for the current state.
    Returns {"intervention": str, "reason": str, "grounded_context": str}.

    memory is the full V2 list (key, value, confidence, source).
    """
    top_state = hypotheses[0]["state"]

    grounded_context = query_buddy_framework(
        f"What does Buddy's framework say about the '{top_state}' state "
        f"and which interventions are recommended?"
    )

    # Exclude last 2 used interventions to force variety
    # recent_interventions is stored as comma-separated string under buddy.recent_interventions
    memory_dict   = memory_to_dict(memory)
    recently_used = [r.strip() for r in memory_dict.get("buddy.recent_interventions", "").split(",") if r.strip()]
    available     = {k: v for k, v in CANDIDATE_INTERVENTIONS.items() if k not in recently_used[-2:]}
    if not available:
        available = CANDIDATE_INTERVENTIONS

    candidates_text = "\n".join([f"- {k}: {v}" for k, v in available.items()])
    hypotheses_text = "\n".join([f"- {h['state']}: {h['confidence']}" for h in hypotheses])
    memory_text     = format_memory_for_prompt(memory)
    obs_text        = "\n".join([f"- {o}" for o in observations])

    prompt = f"""You are the decision-making component of an accountability agent.

Buddy's behavioral framework for this situation (from knowledge base):
{grounded_context}

Observations:
{obs_text}

Hypotheses about the user's current work state (with confidence):
{hypotheses_text}

What Buddy knows about this user (key: value, confidence, source):
{memory_text}

IMPORTANT: Entries with source 'echo' are pattern-level insights based on weeks of data — weight them heavily.
Entries with source 'onboarding' are self-reported at setup — treat as a weak prior only.
Entries with source 'buddy' are recent per-turn observations — use for immediate context.

Candidate interventions available:
{candidates_text}

Choose the ONE intervention that best fits this situation. Consider:
- If observations show the user just stated a concrete plan or next step, choose affirm_and_release.
- If top state is recovery or momentum, choose celebrate_progress.
- If the user seems frustrated with being asked questions, prefer ease_off.
- If memory shows a specific intervention worked before for this state, weigh that heavily.
- Don't ask clarifying questions if the user has already identified their next step.

Respond ONLY with valid JSON, no markdown:
{{"intervention": "<key from candidates>", "reason": "<one sentence explaining why>"}}"""

    response = client.chat.completions.create(
        model="llama-3.1-8b-instant",
        messages=[
            {"role": "system", "content": "You are a decision-making module. Return only valid JSON."},
            {"role": "user",   "content": prompt},
        ],
        temperature=0.3,
    )

    try:
        text = response.choices[0].message.content.strip()
        if text.startswith("```"):
            text = text.split("```")[1].replace("json", "", 1).strip()
        result = json.loads(text)
        if result.get("intervention") not in CANDIDATE_INTERVENTIONS:
            result["intervention"] = "surface_smallest_step"
        result["grounded_context"] = grounded_context
        return result
    except Exception:
        return {
            "intervention":   "surface_smallest_step",
            "reason":         "fallback — decision module returned invalid response",
            "grounded_context": grounded_context,
        }


# ── Progress detector ─────────────────────────────────────────────────────────

PROGRESS_KEYWORDS = [
    "did", "done", "finished", "completed", "took", "took a", "got",
    "%", "percent", "passed", "submitted", "sent", "wrote", "read",
    "studied", "practiced", "watched", "went through", "made it",
]

def log_progress_if_needed(
    user_id: int,
    task_id: int,
    user_message: str,
    detected_state: str,
) -> dict | None:
    """
    Keyword-gates an LLM call — only fires when the message plausibly signals progress.
    If the LLM confirms it, writes a progress_logged or completed event to the DB.
    Returns {"event_type": str, "note": str, "event_id": int}, or None if nothing logged.
    """
    msg = user_message.lower()
    if not any(kw in msg for kw in PROGRESS_KEYWORDS):
        return None

    response = client.chat.completions.create(
        model="llama-3.1-8b-instant",
        messages=[
            {
                "role": "system",
                "content": (
                    "You extract task progress events from user messages. "
                    "If the message clearly describes completing a task, finishing a step, "
                    "or making measurable progress, return JSON with event_type ('progress_logged' or 'completed') and note. "
                    "If it does NOT describe progress (e.g. just chatting, expressing feelings), "
                    "return {\"event_type\": null}. "
                    "Respond ONLY with valid JSON, no markdown."
                ),
            },
            {
                "role": "user",
                "content": f'User message: "{user_message}"',
            },
        ],
        temperature=0.1,
    )

    try:
        text = response.choices[0].message.content.strip()
        if text.startswith("```"):
            text = text.split("```")[1].replace("json", "", 1).strip()
        result = json.loads(text)
        if result.get("event_type"):
            note     = result.get("note", user_message[:120])
            event_id = log_event(
                user_id=user_id,
                event_type=result["event_type"],
                note=note,
                task_id=task_id,
                source="user",  # user said it in chat — treat as self-report
            )
            return {"event_type": result["event_type"], "note": note, "event_id": event_id}
    except Exception:
        pass

    return None


# ── Hook generator (emotion picker path) ─────────────────────────────────────
# Lighter than run_agent() — no conversation saved, no memory updated.
# Used exclusively by /emotion-pick.

EMOTION_CONTEXT = {
    "overwhelmed": "The task feels too big or undefined to approach.",
    "tired":       "The user's energy is low — this isn't laziness, it's depletion.",
    "unclear":     "The user doesn't know where to start — it's a structure problem, not a motivation problem.",
    "bored":       "The task feels unstimulating — engagement, not effort, is what's missing.",
    "anxious":     "There's emotional resistance around this task, possibly fear of failure or judgment.",
}

def generate_hook(user_id: int, task_id: int, emotion: str) -> dict:
    """
    Generate a hook response for the emotion picker notification.
    Does NOT save conversation turns or update memory.
    Returns {"reply": str, "reasoning": dict}.
    """
    task_history   = get_task_history(task_id)
    memory         = get_user_memory(user_id)
    memory_summary = format_memory_for_prompt(memory)
    events         = task_history.get("events", [])
    postpone_count = sum(1 for e in events if e["event_type"] == "postponed")
    task_title     = task_history["task"]["title"] if task_history.get("task") else "your task"
    emotion_ctx    = EMOTION_CONTEXT.get(emotion, "The user is struggling with this task.")

    system_prompt = f"""You are Buddy, a warm accountability companion.

The user just tapped "{emotion}" from a notification — this is their direct self-report.

Write a hook. 1-2 sentences that:
1. Show you already understand why they're stuck (don't ask — you know)
2. Offer one specific insight or reframe that makes them curious to go deeper
3. End on something that makes them want to tap "let's talk"

Do NOT ask a question. Do NOT give advice yet. Do NOT be generic.

Context:
- Task: {task_title}
- Emotion: {emotion} — {emotion_ctx}
- Postponed {postpone_count} time(s)
- Memory: {memory_summary}

Write the hook. Nothing else."""

    response = client.chat.completions.create(
        model="llama-3.1-8b-instant",
        messages=[{"role": "system", "content": system_prompt}],
        temperature=0.7,
    )
    reply = response.choices[0].message.content.strip()

    return {
        "reply": reply,
        "reasoning": {
            "observations":        [f"Emotion picked: {emotion}", f"Task postponed {postpone_count} time(s)"],
            "hypotheses":          [{"state": emotion, "confidence": 0.90}],
            "top_state":           emotion,
            "intervention_chosen": "hook_response",
            "decision_reasoning":  f"User self-reported {emotion} — generating hook to invite deeper conversation",
            "grounded_context":    emotion_ctx,
            "memory_used":         {},
        },
    }


# ── Observations builder ──────────────────────────────────────────────────────

def build_observations(task_history: dict, user_message: str) -> list:
    events = task_history.get("events", [])
    task   = task_history.get("task", {})
    obs    = []

    postpone_count = sum(1 for e in events if e["event_type"] == "postponed")
    if postpone_count > 0:
        obs.append(f"Task postponed {postpone_count} time(s)")

    if events:
        last = events[-1]
        obs.append(f"Last event: {last['event_type']} — {last.get('note', '')}")

    if user_message and not user_message.startswith("[EmotionPick:") and not user_message.startswith("[System:"):
        obs.append(f"User said: \"{user_message}\"")

    if task:
        obs.append(f"Task status: {task.get('status', 'unknown')}")

    return obs


# ── Main agent entry point ────────────────────────────────────────────────────

def run_agent(user_id: int, task_id: int, user_message: str) -> dict:
    """
    Full agent pipeline. Call this for every user message and proactive check-in.

    Args:
        user_id:      ID of the user.
        task_id:      ID of the active task.
        user_message: The user's message, or empty string for agent-initiated check-ins.

    Returns:
        {"reply": str, "reasoning": dict}
    """
    # Gather context — memory is now a list of dicts, not a flat dict
    task_history = get_task_history(task_id)
    memory       = get_user_memory(user_id)       # list[dict]: key, value, confidence, source
    memory_dict  = memory_to_dict(memory)          # flat dict for simple lookups
    conversation = get_conversation_history(user_id)

    # Layer 1 — behavioral signals
    behavioral = detect_behavioral_state(task_history)

    # Layer 2 — keyword scan
    keyword = detect_keyword_state(user_message) if user_message else None

    # Layer 3 — LLM re-classifier, only if layers 1 and 2 disagree
    llm_hypotheses = None
    if keyword and keyword["state"] != behavioral[0]["state"]:
        llm_hypotheses = llm_classify_state(user_message, behavioral)

    hypotheses = merge_hypotheses(behavioral, keyword, llm_hypotheses)
    top_state  = hypotheses[0]["state"]

    observations = build_observations(task_history, user_message)

    # Decision engine
    decision          = decide_intervention(hypotheses, memory, observations)
    intervention      = decision["intervention"]
    decision_reason   = decision["reason"]
    grounded_context  = decision.get("grounded_context", "")
    intervention_goal = CANDIDATE_INTERVENTIONS.get(intervention, "help the user take action")

    # Reasoning snapshot
    reasoning = {
        "observations":        observations,
        "hypotheses":          hypotheses,
        "top_state":           top_state,
        "intervention_chosen": intervention,
        "decision_reasoning":  decision_reason,
        "grounded_context":    grounded_context,
        "memory_used": {
            k: v for k, v in memory_dict.items()
            if k in [
                "buddy.last_detected_state",
                "buddy.recent_interventions",
                f"echo.intervention.effective",
                "onboarding.procrastination_style",
            ]
        },
    }

    # Build system prompt — memory injection now shows confidence + source
    memory_summary  = format_memory_for_prompt(memory)
    history_summary = "\n".join(
        [f"{e['event_type']}: {e.get('note', '')}" for e in task_history.get("events", [])]
    )

    system_prompt = f"""You are a compassionate, proactive accountability companion.
You are NOT a therapist, NOT a productivity guru, NOT a chatbot.
You are an understanding friend who helps people take action.

Your tone: warm, direct, never preachy. One or two sentences max per response.
Never say "Great job!" generically. Praise must be specific and earned.
Never diagnose emotions. Stay in the domain of work states and task behavior.

Current task: {task_history['task']['title'] if task_history.get('task') else 'Unknown'}

Task history:
{history_summary}

What you know about this user (confidence and source shown — trust echo entries most, onboarding least):
{memory_summary}

Detected work state: {top_state}
Your goal for this response: {intervention_goal}

If the user seems to be expressing genuine distress beyond work,
respond with: "It sounds like there's more going on than just this task.
I'm here when you're ready to talk about the work."

CRITICAL RULES:
- Never ask more than ONE question per response.
- If the user expresses frustration or annoyance, stop all questions immediately.
- Sometimes the most helpful thing is silence. A warm "I'm here" beats another question.
- Do not keep breaking tasks down if the user has already agreed to start.
  Once they say they'll do something, just affirm and let them go do it.
"""

    messages = conversation.copy()
    if user_message:
        messages.append({"role": "user", "content": user_message})

    if not user_message:
        injection = (
            "[System: Initiate the first check-in. Speak first.]"
            if not messages else
            "[System: A day has passed since the last check-in. The user has not taken action. "
            "Initiate a proactive check-in based on what you know about them and what they last said.]"
        )
        messages = messages + [{"role": "user", "content": injection}]

    response = client.chat.completions.create(
        model="llama-3.1-8b-instant",
        messages=[
            {"role": "system", "content": system_prompt},
            *[{"role": msg.get("role", "user"), "content": msg.get("content", "")} for msg in messages],
        ],
        temperature=0.7,
    )
    reply = response.choices[0].message.content.strip()

    # Persist conversation turn — skip internal agent signals
    is_internal = (
        user_message.startswith("[System") or
        user_message.startswith("[EmotionPick:")
    )
    if user_message and not is_internal:
        save_conversation_turn(user_id, "user", user_message, task_id=task_id)
    if not user_message.startswith("[EmotionPick:"):
        save_conversation_turn(user_id, "assistant", reply, task_id=task_id, reasoning=json.dumps(reasoning))

    # Log progress if user message signals it
    progress_logged = None
    if user_message and not is_internal:
        progress_logged = log_progress_if_needed(user_id, task_id, user_message, top_state)
    if progress_logged:
        reasoning["progress_logged"] = progress_logged

    # Update memory — V2 key names, confidence, source
    update_memory(user_id, "buddy.last_detected_state", top_state,    confidence=0.5, source="buddy")
    update_memory(user_id, "buddy.last_intervention",   intervention,  confidence=0.5, source="buddy")

    recent = [r.strip() for r in memory_dict.get("buddy.recent_interventions", "").split(",") if r.strip()]
    recent.append(intervention)
    update_memory(user_id, "buddy.recent_interventions", ",".join(recent[-3:]), confidence=0.5, source="buddy")

    return {"reply": reply, "reasoning": reasoning}